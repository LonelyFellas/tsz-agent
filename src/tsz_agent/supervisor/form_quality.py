"""Keep generated English forms within the configured grammatical slots."""

import re
from collections.abc import Sequence

from tsz_agent.form_candidates import CandidateForm, CandidatePos, CandidateVariant

NEGATIVE_AUXILIARIES = frozenset(
    "am are is was were be can could dare do does did had has have may might must "
    "need ought shall should will would".split()
)
COMPARISON_MARKERS = ("comparative", "superlative")


def dictionary_variant(variant: CandidateVariant, *, rhotic: bool) -> CandidateVariant | None:
    phonetic = variant.dict_phonetic.strip().replace("(r)", "r" if rhotic else "")
    inner = phonetic
    if phonetic.startswith("/") and phonetic.endswith("/"):
        inner = phonetic[1:-1].strip()
    elif phonetic.startswith("[") and phonetic.endswith("]"):
        inner = phonetic[1:-1].strip()
    if not inner or re.search(r"[/()\[\]{}|,;]", inner):
        return None
    return variant.model_copy(update={"dict_phonetic": phonetic})


def same_ing_slots(pos: str, allowed: set[str]) -> tuple[str, str] | None:
    if pos == "verb" and {"present_participle", "verb_gerund"} <= allowed:
        return "present_participle", "verb_gerund"
    if pos != "phrase_verbal_constituent":
        return None
    # Scoped phrase codes generated by the catalog can retain a truncated type
    # name and a suffix. Only use an unambiguous configured pair.
    participles = [
        code
        for code in allowed
        if code == "phrase_present_participle"
        or re.fullmatch(r"phrase_present__[a-f0-9]{16}", code)
    ]
    gerunds = [
        code
        for code in allowed
        if code == "phrase_gerund" or re.fullmatch(r"phrase_gerund_[a-f0-9]{16}", code)
    ]
    if len(participles) == len(gerunds) == 1:
        return participles[0], gerunds[0]
    return None


def listed_comparison(form: CandidateForm, references: Sequence[str]) -> bool:
    for excerpt in references:
        for listing in re.findall(r" · 词形 [^\[]*\[([^\]]*)\]", excerpt):
            if any(
                re.search(rf"(?<![\w'-]){re.escape(variant.spelling)}(?![\w'-])", listing, re.I)
                for variant in (form.uk, form.us)
            ):
                return True
    return False


def lists_adjective(references: Sequence[str]) -> bool:
    return any(
        re.search(r"\b(?:adjective|adj)\b|形容[词詞]", label, re.I)
        for excerpt in references
        for label in re.findall(r" · 词性 ([^·]+)", excerpt)
    )


def keep_dictionary_forms(
    row: CandidatePos,
    allowed: set[str],
    headword: str,
    references: Sequence[str],
    *,
    also_noun_or_verb: bool,
) -> list[CandidateForm]:
    forms: dict[str, CandidateForm] = {}
    lemma = headword.casefold()
    for form in row.forms:
        code = form.form_type
        if code not in allowed or code in forms:
            continue
        if code == "verb_negative_contraction" and lemma not in NEGATIVE_AUXILIARIES:
            continue
        if any(marker in code for marker in COMPARISON_MARKERS) and (
            all(variant.spelling.casefold() == lemma for variant in (form.uk, form.us))
            or (also_noun_or_verb and not listed_comparison(form, references))
        ):
            continue
        uk = dictionary_variant(form.uk, rhotic=False)
        us = dictionary_variant(form.us, rhotic=True)
        if uk is not None and us is not None:
            forms[code] = form.model_copy(update={"uk": uk, "us": us})
    if pair := same_ing_slots(row.pos, allowed):
        first, second = pair
        if first in forms and second not in forms:
            forms[second] = forms[first].model_copy(update={"form_type": second})
        elif second in forms and first not in forms:
            forms[first] = forms[second].model_copy(update={"form_type": first})
    return list(forms.values())
